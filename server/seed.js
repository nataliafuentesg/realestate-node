async function seed() {
  await mongoose.connect(process.env.MONGO_URI)
  console.log('MongoDB connected')

  const withExtras = properties.map((p) => ({
    ...p,
    features: pickFeatures(),
    ...pickAgent(),
  }))

  const created = await Property.insertMany(withExtras)
  console.log(`Seeded ${created.length} properties`)

  await mongoose.disconnect()
  process.exit(0)
}

seed().catch((err) => {
  console.error(err)
  process.exit(1)
})
